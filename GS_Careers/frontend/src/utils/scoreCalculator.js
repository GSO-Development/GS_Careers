export const parseNumericSalary = (val) => {
    if (!val) return null;
    let s = String(val).toLowerCase().trim();
    if (!s || s === 'not mentioned' || s === 'not specified' || s === '0') return null;

    const rangeMatch = s.match(/([\d,]+(?:\.\d+)?)\s*k?\s*[\-\–to]+\s*([\d,]+(?:\.\d+)?)\s*k?/i);
    if (rangeMatch) {
        let minV = parseFloat(rangeMatch[1].replace(/,/g, ''));
        let maxV = parseFloat(rangeMatch[2].replace(/,/g, ''));
        if (s.includes('k') && minV < 1000) minV *= 1000;
        if (s.includes('k') && maxV < 1000) maxV *= 1000;
        return (minV + maxV) / 2;
    }

    let clean = s.replace(/[^0-9.]/g, '');
    if (!clean) return null;
    let num = parseFloat(clean);
    if (isNaN(num) || num <= 0) return null;
    if (s.includes('k') && num < 1000) num *= 1000;
    return num;
};

export const calculateSalaryMatchScore = (salaryExpectation, minSalary, maxSalary) => {
    let jobMin = minSalary ? parseFloat(minSalary) : null;
    let jobMax = maxSalary ? parseFloat(maxSalary) : null;

    if (jobMin && jobMax && jobMin > jobMax) {
        const temp = jobMin;
        jobMin = jobMax;
        jobMax = temp;
    }

    if (!jobMin && !jobMax) {
        return { score: 100, status: 'no_budget_defined', message: 'No budget range set for job' };
    }

    const candSal = parseNumericSalary(salaryExpectation);
    if (candSal === null) {
        return { score: 80, status: 'unspecified', message: 'Candidate salary expectation not mentioned' };
    }

    if (jobMin && jobMax) {
        if (candSal >= jobMin && candSal <= jobMax) {
            return { score: 100, status: 'within_range', message: 'Within expected salary budget' };
        } else if (candSal < jobMin) {
            return { score: 100, status: 'below_range', message: 'Below expected salary budget' };
        } else {
            const excess = (candSal - jobMax) / jobMax;
            const penaltyScore = Math.max(10, Math.round(100 - (excess * 150)));
            return { score: penaltyScore, status: 'above_range', message: `${Math.round(excess * 100)}% above max budget` };
        }
    } else if (jobMax) {
        if (candSal <= jobMax) {
            return { score: 100, status: 'within_range', message: 'Within maximum budget' };
        } else {
            const excess = (candSal - jobMax) / jobMax;
            const penaltyScore = Math.max(10, Math.round(100 - (excess * 150)));
            return { score: penaltyScore, status: 'above_range', message: `${Math.round(excess * 100)}% above max budget` };
        }
    } else if (jobMin) {
        if (candSal <= jobMin * 1.25) {
            return { score: 100, status: 'within_range', message: 'Within expected budget' };
        } else if (candSal < jobMin) {
            return { score: 100, status: 'below_range', message: 'Below expected budget' };
        } else {
            const excess = (candSal - jobMin) / jobMin;
            const penaltyScore = Math.max(10, Math.round(100 - (excess * 120)));
            return { score: penaltyScore, status: 'above_range', message: `${Math.round(excess * 100)}% above minimum budget` };
        }
    }

    return { score: 100, status: 'within_range', message: 'Matched' };
};

